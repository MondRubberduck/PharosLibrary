#!/usr/bin/env python3
"""
make_sandbox.py -- create the throwaway UE conversion sandbox locally, or
bring an existing one up to date.

The sandbox is NOT shipped in the repo on purpose: it is an empty UE
project whose whole job is to be a temporary workspace (pack Content is
robocopied INTO it, the headless engine run exports OUT of it, sources
stay read-only). It carries an EngineAssociation that must match the
machine's own UE install -- so it is generated here, on this machine,
from the UE_EXE you configured, instead of shipping a version-pinned
file that goes stale.

Creates (beside this script, or under --out):
    sandbox/Sandbox.uproject      empty project: the Python plugin on, the
                                  store plugins off
    sandbox/Content/              where convert_packs.sh copies pack sources

The store plugins (Fab, Bridge) are switched off because the Epic launcher
updates them apart from the engine. One that is newer than the engine
cannot load, the engine asks a question nobody answers in an unattended
run, and exits before the export script starts.

Safe to delete and regenerate at any time; safe to re-run: an existing
sandbox is left alone when it is current, and only its project file is
rewritten when it is not (another engine version, a plugin entry missing).
Content/ is never touched. `pharos.py convert` runs this before every
conversion.

Usage:
    python make_sandbox.py [--out DIR] [--engine-version X.Y] [--force]
    (UE_EXE env or --engine-version sets EngineAssociation; without
     either an existing value is kept, and a new file goes without the
     field -- harmless for headless driver runs, which always invoke one
     specific UnrealEditor-Cmd binary.)
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

# engine plugins a headless export never needs and must not wait for
OFF = ("Fab", "Bridge")

UPROJECT = {
    "FileVersion": 3,
    "Category": "",
    "Description": "Pharos conversion sandbox - throwaway empty project "
                   "generated by make_sandbox.py. Pack sources are copied "
                   "in temporarily and never modified in place. Safe to "
                   "delete and regenerate.",
    "Plugins": [{"Name": "PythonScriptPlugin", "Enabled": True}]
               + [{"Name": name, "Enabled": False} for name in OFF],
}


def engine_version_from_ue_exe(ue_exe: str) -> str | None:
    """'.../UE_5.7/Engine/Binaries/Win64/UnrealEditor-Cmd.exe' -> '5.7'."""
    m = re.search(r"UE_(\d+\.\d+)", ue_exe or "")
    return m.group(1) if m else None


def _plugins(doc: dict | None) -> list:
    """The plugin entries of a project file that are entries at all (a
    hand-edited file may hold anything there)."""
    plugins = (doc or {}).get("Plugins")
    return [p for p in plugins if isinstance(p, dict)] if isinstance(plugins, list) else []


def project_doc(existing: dict | None, version: str | None) -> dict:
    """The project file as it should be now. From an existing file only
    two things are kept: plugin entries this script does not set (somebody
    switched another plugin off by hand) and, when no engine version is
    known, the association already there."""
    doc = {k: v for k, v in UPROJECT.items() if k != "Plugins"}
    ours = {p["Name"] for p in UPROJECT["Plugins"]}
    kept = [p for p in _plugins(existing)
            if isinstance(p.get("Name"), str) and p["Name"] and p["Name"] not in ours]
    doc["Plugins"] = [dict(p) for p in UPROJECT["Plugins"]] + kept
    assoc = version or (existing or {}).get("EngineAssociation")
    if assoc:
        doc["EngineAssociation"] = assoc
    return doc


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--out", default=None,
                    help="target dir (default: sandbox/ beside this script)")
    ap.add_argument("--engine-version", default=None, dest="engine_version",
                    help="EngineAssociation, e.g. 5.7 (default: derived "
                         "from UE_EXE; an existing value is kept otherwise)")
    ap.add_argument("--force", action="store_true",
                    help="write the project file anew, keeping nothing "
                         "from an existing one")
    args = ap.parse_args()

    target = (Path(args.out).resolve() if args.out else
              Path(__file__).resolve().parent / "sandbox")
    uproject = target / "Sandbox.uproject"
    version = args.engine_version or engine_version_from_ue_exe(
        os.environ.get("UE_EXE", ""))

    existing = None
    if uproject.is_file() and not args.force:
        try:
            existing = json.loads(uproject.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            existing = None                 # unreadable: written anew
        if not isinstance(existing, dict):
            existing = None
    doc = project_doc(existing, version)
    if existing == doc:
        print(f"sandbox already exists and is current: {uproject}")
        return 0

    was_there = uproject.is_file()
    (target / "Content").mkdir(parents=True, exist_ok=True)
    uproject.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")

    assoc = doc.get("EngineAssociation") or \
        "(none - headless driver runs pass the binary explicitly)"
    if was_there and existing is not None:
        print(f"sandbox updated: {uproject}")
        old = existing.get("EngineAssociation")
        if old != doc.get("EngineAssociation"):
            print(f"  engine association: {old or '(none)'} -> {assoc}")
        had = {p.get("Name") for p in _plugins(existing) if isinstance(p.get("Name"), str)}
        new_off = [n for n in OFF if n not in had]
        if new_off:
            print(f"  switched off: {', '.join(new_off)} (store plugins; one that is "
                  f"newer than the engine ends an unattended run)")
        print("  Content/ left as it was")
        return 0
    print(f"sandbox {'written anew' if was_there else 'created'}: {uproject}")
    print(f"  engine association: {assoc}")
    print(f"  plugins: PythonScriptPlugin on; {', '.join(OFF)} off")
    if not was_there:
        print("next: re-run your convert_packs.sh / relink_pack.sh command")
    return 0


if __name__ == "__main__":
    sys.exit(main())
