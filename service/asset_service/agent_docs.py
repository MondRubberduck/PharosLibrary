def _counts(db_path: str) -> dict:
    try:
        conn = sqlite3.connect(db_path)
    except sqlite3.OperationalError as exc:
        # A fresh install has no registry yet: `init` does not create it, the
        # first serve/scanner run does.  Say so in plain words instead of
        # letting sqlite3.OperationalError escape as a traceback.
        raise SystemExit(
            "cannot read the registry: %s\n"
            "  (%s)\n"
            "The registry does not exist yet.  Start the server once\n"
            "  python pharos.py serve\n"
            "or scan a folder, then run `python pharos.py docs` again."
            % (db_path, exc))
    out: dict = {}
    def one(key, sql):
        try:
            out[key] = conn.execute(sql).fetchone()[0]
        except sqlite3.OperationalError:
            out[key] = 0
    one("meshes", "SELECT COUNT(*) FROM meshes")
    one("mesh_packs", "SELECT COUNT(DISTINCT pack) FROM meshes")
    one("textures", "SELECT COUNT(*) FROM textures")
    one("audio", "SELECT COUNT(*) FROM audio")
    one("collection", "SELECT COUNT(*) FROM collection")
    one("local", "SELECT COUNT(*) FROM collection WHERE availability='local'")
    # same "no measured dimensions" rule as the API's unmeasured_excluded
    one("unmeasured", "SELECT COUNT(*) FROM meshes WHERE COALESCE(max_dim, 0) = 0")
    try:
        out["clips"] = db.anim_clip_count(conn, config.SECTIONS.get("animation"))
    except sqlite3.OperationalError:
        out["clips"] = 0
    conn.close()
    try:
        out["previews"] = len(list(config.PREVIEW_DIR.glob("*.webm"))) \
            if config.PREVIEW_DIR.is_dir() else 0
    except OSError:
        out["previews"] = 0
    return out


